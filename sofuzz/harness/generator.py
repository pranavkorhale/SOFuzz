    def __init__(self, so_path: str, output_dir: str = DEFAULT_HARNESS_DIR):
        self.so_path = os.path.abspath(so_path)
        self.output_dir = output_dir
        self.logger = get_logger()
        
        FileUtils.ensure_dir(output_dir)
        
        so_name = FileUtils.get_file_name(so_path)
        self.harness_dir = os.path.join(output_dir, so_name)
        FileUtils.ensure_dir(self.harness_dir)
    
    def generate_for_function(
        self,
        function_name: str,
        timeout: int = 2,
        max_input_size: int = 1024 * 1024,
        is_jni: bool = False
    ) -> GeneratedHarness:
        """Generate harness for a specific function"""
        harness = GeneratedHarness(
            function_name=function_name,
            source_path="",
            so_path=self.so_path
        )
        
        try:
            # Select template
            if is_jni:
                template = self.HARNESS_JNI_TEMPLATE
            else:
                template = self.HARNESS_TEMPLATE
                
            # Phase 2 Constraint Inference Heuristics
            lower_name = function_name.lower()
            if any(x in lower_name for x in ["password", "key", "token", "hash"]):
                max_input_size = min(max_input_size, 32)
                self.logger.info(f"Constraint Engine: Capped payload to 32 bytes for strict validation logic ({function_name})")
            elif any(x in lower_name for x in ["char", "string", "name", "str", "crashme"]):
                max_input_size = min(max_input_size, 14)
                self.logger.info(f"Constraint Engine: Strings capped to 14 bytes avoiding trivial FP overflows ({function_name})")
            
            
            # Generate source code
            source_code = template.format(
                function_name=function_name,
                so_path=self.so_path,
                timeout=timeout,
                max_input_size=max_input_size
            )
            
            # Write source file
            source_filename = f"harness_{function_name}.c"
            source_path = os.path.join(self.harness_dir, source_filename)
            
            FileUtils.write_text(source_path, source_code)
            
            harness.source_path = source_path
            harness.is_generated = True
            
            self.logger.info(f"Generated harness: {source_path}")
            
        except Exception as e:
            harness.error = str(e)
            self.logger.error(f"Harness generation failed: {e}")
        
        return harness
    
    def generate_for_all(
        self,
        functions: List[FunctionInfo],
        timeout: int = 2,
        max_input_size: int = 1024 * 1024
    ) -> List[GeneratedHarness]:
        """
        Generate harnesses for all functions
        
        Args:
            functions: List of FunctionInfo from analyzer
            timeout: Execution timeout
            max_input_size: Maximum input size
        
        Returns:
            List of GeneratedHarness objects
        """
        harnesses = []
        
        self.logger.info(f"Generating harnesses for {len(functions)} functions")
        
        for func in functions:
            harness = self.generate_for_function(
                function_name=func.name,
                timeout=timeout,
                max_input_size=max_input_size,
                is_jni=func.is_jni
            )
            harnesses.append(harness)
        
        successful = sum(1 for h in harnesses if h.is_generated)
        self.logger.success(f"Generated {successful}/{len(functions)} harnesses")
        
        # Phase 2 Sequence Validation 
        # Attempt to create sequence tests if we have multiple JNI methods
        jni_funcs = [f for f in functions if f.is_jni]
        if len(jni_funcs) > 1:
            seq_harness = self.generate_sequence_harness(jni_funcs, timeout, max_input_size)
            if seq_harness.is_generated:
                harnesses.append(seq_harness)
        
        return harnesses

    def generate_sequence_harness(self, functions: List[FunctionInfo], timeout: int = 2, max_input_size: int = 1024 * 1024) -> GeneratedHarness:
        """Phase 2: Generate multi-method sequence harnesses (e.g. out-of-order execution)"""
        harness = GeneratedHarness(
            function_name="sequence_combo",
            source_path="",
            so_path=self.so_path
        )
        try:
            self.logger.info(f"Building Call Sequence Validation harness for {len(functions)} native endpoints")
            calls = []
            for i, f in enumerate(functions):
                calls.append(f'        jni_func_t func{i} = (jni_func_t)dlsym(handle, "{f.name}");')
                calls.append(f'        if (func{i}) func{i}(NULL, NULL, buffer, (jint)size);')

            source_code = self.HARNESS_SEQ_TEMPLATE.format(
                so_path=self.so_path,
                timeout=timeout,
                max_input_size=max_input_size,
                call_sequence="\n".join(calls)
            )
            
            source_filename = "harness_sequence_combo.c"
            source_path = os.path.join(self.harness_dir, source_filename)
            FileUtils.write_text(source_path, source_code)
            
            harness.source_path = source_path
            harness.is_generated = True
            self.logger.success(f"Generated Call Sequence validation harness: {source_path}")
            
        except Exception as e:
            harness.error = str(e)
            self.logger.error(f"Sequence generator failed: {e}")
            
        return harness
    
    def get_harness_path(self, function_name: str) -> str:
        """Get path to harness source file"""
        return os.path.join(self.harness_dir, f"harness_{function_name}.c")
    
    def get_binary_path(self, function_name: str) -> str:
        """Get path to compiled harness binary"""
        return os.path.join(self.harness_dir, f"harness_{function_name}")
    
    def list_generated_harnesses(self) -> List[str]:
        """List all generated harness files"""
        if not os.path.exists(self.harness_dir):
            return []
        
        harnesses = []
        for filename in os.listdir(self.harness_dir):
            if filename.startswith("harness_") and filename.endswith(".c"):
                harnesses.append(os.path.join(self.harness_dir, filename))
        
        return harnesses
    
    def cleanup(self) -> None:
        """Remove all generated harnesses"""
        if os.path.exists(self.harness_dir):
            FileUtils.delete_dir(self.harness_dir)
            self.logger.info(f"Cleaned up: {self.harness_dir}")